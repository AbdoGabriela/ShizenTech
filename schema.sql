CREATE DATABASE IF NOT EXISTS termometro CHARACTER SET utf8mb4;
USE termometro;

CREATE TABLE IF NOT EXISTS respostas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    criado_em DATETIME DEFAULT CURRENT_TIMESTAMP,
    q1 TINYINT NOT NULL, q2 TINYINT NOT NULL, q3 TINYINT NOT NULL,
    q4 TINYINT NOT NULL, q5 TINYINT NOT NULL, q6 TINYINT NOT NULL,
    total TINYINT NOT NULL,
    faixa ENUM('equilibrio','atencao','cuidado') NOT NULL,
    CHECK (q1 BETWEEN 0 AND 10 AND q2 BETWEEN 0 AND 10 AND q3 BETWEEN 0 AND 10
       AND q4 BETWEEN 0 AND 10 AND q5 BETWEEN 0 AND 10 AND q6 BETWEEN 0 AND 10)
);
